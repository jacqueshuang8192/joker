--把牌值转换成字符串并取出对应的字符串
function LoadCard.changeCardsString(card1, card2)
    if card2>card1 then
        card1, card2 = card2, card1
    end
	local CardFrom = tostring(card1) .. "_" .. tostring(card2)
    
    for k,v in pairs(LoadCard.Cardtable) do
       if k == CardFrom then
           return v
       end
   end
   return "0"
end



