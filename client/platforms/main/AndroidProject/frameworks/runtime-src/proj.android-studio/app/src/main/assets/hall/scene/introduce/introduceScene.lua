    local floor = layout:getChildByName("floor")

    local btn_close = floor:getChildByName("btn_close")
    btn_close:addTouchEventListener(

        function(sender,event)

            if event == TOUCH_EVENT_BEGAN then
                sender:setScale(0.8)
            end

            --触摸取消
            if event == TOUCH_EVENT_CANCELED then
                sender:setScale(1.0)
            end

            --触摸结束
            if event == TOUCH_EVENT_ENDED then
                sender:setScale(1.0)

                self:removeScene()

            end

        end
    )

    local web_plane = floor:getChildByName("web_plane")

    self:showGameList(currentPlayMode)

